import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = dirname(fileURLToPath(import.meta.url));
const engine = join(root, "native-copy/bin/Debug/net8.0/DwgEngineQualification.dll");
const source = readFileSync(join(root, "geometry-integration-green/generated-fixture/synthetic-input.dwg"));
const sha = bytes => createHash("sha256").update(bytes).digest("hex");
const evidence = join(root, "framed-evidence-green");
mkdirSync(evidence);
const runs = [];
for (const name of ["wrapped", "full-turn", "nonzero-full-turn"]) {
  const request = readFileSync(join(root, `geometry-integration-green/${name}-edit-request.json`));
  const header = Buffer.alloc(16);
  header.write("1HKRSV01"); header.writeUInt32BE(request.length, 8); header.writeUInt32BE(source.length, 12);
  const input = Buffer.concat([header, request, source]);
  const run = spawnSync("/opt/homebrew/bin/dotnet", [engine, "resave-native-stdio"], { input, maxBuffer: 211000000, timeout: 120000 });
  assert.equal(run.status, 0); assert.equal(run.stderr.length, 0);
  const frame = run.stdout;
  assert.equal(frame.subarray(0, 8).toString(), "1HKRSO01");
  const reportLength = frame.readUInt32BE(8), dwgLength = frame.readUInt32BE(12);
  assert.equal(frame.length, 16 + reportLength + dwgLength);
  const reportBytes = frame.subarray(16, 16 + reportLength), dwg = frame.subarray(16 + reportLength);
  const report = JSON.parse(reportBytes);
  assert.equal(report.source.sha256, sha(source)); assert.equal(report.request.sha256, sha(request)); assert.equal(report.output.sha256, sha(dwg));
  assert.equal(report.verification.inventoriedEntityCount, 9);
  const read = spawnSync("/opt/homebrew/bin/dotnet", [engine, "read-native-stdio"], { input: dwg, maxBuffer: 33554432, timeout: 120000 });
  assert.equal(read.status, 0); assert.equal(read.stderr.length, 0);
  const actual = JSON.parse(read.stdout);
  const verifiedFlow = JSON.parse(readFileSync(join(root, `geometry-integration-green/${name}-readback/native-import.json`)));
  assert.deepEqual(actual.entities, verifiedFlow.entities);
  assert.equal(actual.entities.find(entity => entity.type === "LINE").geometry.end[0], name === "wrapped" ? 120 : 100);
  writeFileSync(join(evidence, `${name}.input.frame`), input, { flag: "wx" });
  writeFileSync(join(evidence, `${name}.output.frame`), frame, { flag: "wx" });
  writeFileSync(join(evidence, `${name}.report.json`), reportBytes, { flag: "wx" });
  writeFileSync(join(evidence, `${name}.dwg`), dwg, { flag: "wx" });
  writeFileSync(join(evidence, `${name}.readback.json`), read.stdout, { flag: "wx" });
  runs.push({ name, exitCode: run.status, stderrBytes: run.stderr.length, sourceSha256: sha(source), requestSha256: sha(request), outputSha256: sha(dwg), frameSha256: sha(frame) });
}
assert.equal(sha(readFileSync(join(root, "geometry-integration-green/generated-fixture/synthetic-input.dwg"))), sha(source));
const summary = { engine, engineSha256: sha(readFileSync(engine)), runs };
writeFileSync(join(evidence, "summary.json"), JSON.stringify(summary, null, 2), { flag: "wx" });
console.log(JSON.stringify(summary, null, 2));
